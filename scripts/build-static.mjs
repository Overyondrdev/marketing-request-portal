#!/usr/bin/env node
// Bundle the app's files (public/) into the Worker script, so a deploy is one script upload and every file is served
// by the Worker after the sign-in check. Writes src/generated/static.js (git-ignored). Runs automatically before
// `wrangler dev` / `wrangler deploy` (build.command in wrangler.jsonc) and before typecheck and tests.
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = 'public';
const TYPES = {
  html: 'text/html; charset=utf-8',
  css: 'text/css; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  svg: 'image/svg+xml',
  txt: 'text/plain; charset=utf-8',
  json: 'application/json; charset=utf-8',
  woff2: 'font/woff2',
  png: 'image/png',
  jpg: 'image/jpeg',
  webp: 'image/webp',
  ico: 'image/x-icon',
};
const TEXT = new Set(['html', 'css', 'js', 'svg', 'txt', 'json']);

const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      walk(p);
      continue;
    }
    const ext = name.split('.').pop().toLowerCase();
    if (!TYPES[ext]) throw new Error(`build-static: no content type for ${p}; add one to scripts/build-static.mjs`);
    const buf = readFileSync(p);
    const path = '/' + relative(ROOT, p).split(sep).join('/');
    files[path] = {
      type: TYPES[ext],
      etag: '"' + createHash('sha256').update(buf).digest('base64url').slice(0, 22) + '"',
      ...(TEXT.has(ext) ? { text: buf.toString('utf8') } : { b64: buf.toString('base64') }),
    };
  }
})(ROOT);

mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/static.js',
  `// Generated by scripts/build-static.mjs from public/. Do not edit.\nexport default ${JSON.stringify(files)};\n`,
);
console.log(`build-static: ${Object.keys(files).length} files bundled`);
